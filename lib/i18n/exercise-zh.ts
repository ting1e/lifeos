// ---------------------------------------------------------------------------
// Helper — translate a catalog value for the given locale.
// ---------------------------------------------------------------------------

export type CatalogField = "bodyPart" | "equipment" | "target" | "muscleGroup" | "category";

const CATALOG_MAP: Record<CatalogField, Record<string, string>> = {
  bodyPart: bodyPartZh,
  equipment: equipmentZh,
  target: targetZh,
  muscleGroup: muscleGroupZh,
  category: categoryZh,
};

export function trCatalog(
  field: CatalogField,
  value: string | null | undefined,
  locale: Locale,
): string | null {
  if (!value) return null;
  if (locale !== "zh") return value;
  return CATALOG_MAP[field][value] ?? value;
}

